import requests
import time as tm
# Dictionary that maps categories to related keywords
# These keywords will be used to classify story titles
CATEGORIES = {
    "technology": ["AI", "software", "tech", "code", "computer", "data", "cloud", "API", "GPU", "LLM"],
    "worldnews": ["war", "government", "country", "president", "election", "climate", "attack", "global"],
    "sports": ["NFL", "NBA", "FIFA", "sport", "game", "team", "player", "league", "championship"],
    "science": ["research", "study", "space", "physics", "biology", "discovery", "NASA", "genome"],
    "entertainment": ["movie", "film", "music", "Netflix", "game", "book", "show", "award", "streaming"],
}
# Custom header to avoid request blocking
headers = {"User-Agent": "TrendPulse/1.0"}
# API endpoints
top_story_IDs = "https://hacker-news.firebaseio.com/v0/topstories.json"
item_url = "https://hacker-news.firebaseio.com/v0/item/{id}.json"


# ── Step 1: Get the list of top story IDs ──────────────────────────
def get_top_story_ids():
    try:
        response = requests.get(top_story_IDs, headers=headers, timeout=5)
        response.raise_for_status()
        ids = response.json()
        return ids[:100]          # fetch the first 20 as instructed
    except requests.RequestException as e:
        print(f"Failed to fetch story IDs: {e}")
        return []

# ── Step 2: Get each story's details ──────────────────────────────
def get_story_details(story_id):

    try:
      response = requests.get(item_url.format(id=story_id), headers=headers, timeout=5)
      response.raise_for_status()
      story = response.json()
      return story
    except requests.RequestException as e:
      print(f"Failed to fetch story details for ID {story_id}: {e}")
      return None

# ── Step 3: Categorize stories by title keywords ──────────────────
def categorise_by_story(title):
    title = title.lower()
    for category, keywords in CATEGORIES.items():
        if any(keyword.lower() in title for keyword in keywords):
            return category
    return "other" # Default category if no keywords match


def main():
    print("Fetching top story IDs...")
    top_story_ids = get_top_story_ids()
    print(f"Fetched {len(top_story_ids)} IDs. Fetching details...\n")


    # Fetch all story details first
    all_stories = []
    for story_id in top_story_ids:
      story = get_story_details(story_id)
      if story:
        all_stories.append(story)

    # Group stories into categories
    categorized_stories = {}
    for story in all_stories:
      title = story.get("title", "")
      category = categorise_by_story(title)
      if category not in categorized_stories:
        categorized_stories[category] = []
      categorized_stories[category].append(title)


    # Print results with delay
    print("Top Stories by Category:")
    for category, titles in categorized_stories.items():
        print(f"\nCategory: {category}")
        print(f"Total: {len(titles)}")
        # Print only the first 3 titles for brevity
        for t in titles[:3]:
            print(f"- {t}")
        tm.sleep(2) # Wait 2 seconds between each category


if __name__ == "__main__":
    main()


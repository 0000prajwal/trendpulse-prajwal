import requests
from datetime import datetime
import json
import os

# API base URL
BASE_URL = "https://hacker-news.firebaseio.com/v0"

# Simple category function (you already used this logic)
def categorize(title):
    if not title:
        return "uncategorized"

    title_lower = title.lower()

    # Technology
    if any(word in title_lower for word in [
        "ai", "llm", "tech", "software", "code", "computer",
        "data", "cloud", "api", "gpu", "iphone", "youtube", "copilot"
    ]):
        return "technology"

    # Sports
    elif any(word in title_lower for word in [
        "game", "player", "team", "match", "league", "football", "cricket"
    ]):
        return "sports"

    # Science
    elif any(word in title_lower for word in [
        "research", "study", "space", "physics", "biology", "nasa"
    ]):
        return "science"

    # Entertainment
    elif any(word in title_lower for word in [
        "movie", "film", "music", "show", "netflix", "series"
    ]):
        return "entertainment"

    # World News
    elif any(word in title_lower for word in [
        "government", "war", "election", "country", "president"
    ]):
        return "worldnews"

    return "uncategorized"

# Extract required fields
def extract_fields(story):
    return {
        "post_id": story.get("id"),
        "title": story.get("title", ""),
        "category": categorize(story.get("title", "")),
        "score": story.get("score", 0),
        "num_comments": story.get("descendants", 0),
        "author": story.get("by", ""),
        "collected_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    }


# Get top story IDs
def get_top_story_ids():
    response = requests.get(f"{BASE_URL}/topstories.json")
    return response.json()[:122]   # keep small for fast run


# Get story details
def get_story_details(story_id):
    try:
        response = requests.get(f"{BASE_URL}/item/{story_id}.json")
        return response.json()
    except:
        print(f"Skipping story {story_id}")
        return None


# Main
def main():
    ids = get_top_story_ids()

    extracted_stories = []

    for sid in ids:
        story = get_story_details(sid)

        if story and "title" in story:
            cleaned = extract_fields(story)
            extracted_stories.append(cleaned)

    # Create data directory if it doesn't exist
    data_dir = "data/"
    os.makedirs(data_dir, exist_ok=True)

    # Generate filename with current date
    current_date = datetime.now().strftime("%Y%m%d")
    filename = os.path.join(data_dir, f"trends_{current_date}.json")

    # Save stories to JSON file
    with open(filename, "w") as f:
        json.dump(extracted_stories, f, indent=4)

    print(f"\nCollected {len(extracted_stories)} stories. Saved to {filename}")

    # Print sample output
    print("\nExtracted Stories (first 7 for sample):\n")
    for s in extracted_stories[:7]:
        print(s)


if __name__ == "__main__":
    main()